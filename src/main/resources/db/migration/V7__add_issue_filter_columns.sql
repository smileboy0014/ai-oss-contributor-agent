-- 이슈 #9 — 규칙 필터가 판정을 적재할 자리
--
-- ⚠ 머지 순서: V6(#8 이슈 커서) → V7(여기). baseline-on-migrate 가 false 라
--   순서가 역전되면 Flyway 가 out-of-order 로 보고 validate 에서 기동을 막는다.
--   H2 는 매번 새로 떠서 드러나지 않고 PostgreSQL 개발 DB 에서만 터진다 — Q-2b.
--
-- ⚠ 벤더 고유 문법을 쓰지 않는다 (Q-2). H2·PostgreSQL 양쪽에서 같은 SQL 이 돈다.
--   ALTER COLUMN ... SET DATA TYPE 은 양쪽 공통 문법이다.

-- ─────────────────────────────────────────────────────────────
-- 1) 코멘트 수 — 수집은 하는데 버리고 있었다
-- ─────────────────────────────────────────────────────────────
-- IssueSnapshot.commentCount 는 #8 이 「이슈 #9 를 위해」 수집해 놓고 영속하지 않았다.
-- 규칙 ③ 의 입력이고, #11 의 LLM 판정에도 그대로 쓰인다.
--
-- 🔴 이 값으로 배제하지 않는다. 논의가 길면 요구가 불명확할 확률이 높지만 인과가
--   아니다 — 활발한 논의일 수도 있다. 판정은 UNDECIDED(보류)이고 LLM 이 본다.
ALTER TABLE issue
    ADD COLUMN comment_count INTEGER;

-- ─────────────────────────────────────────────────────────────
-- 2) 우선순위 점수 — 계산하고 버릴 곳이 없었다 (FR-4)
-- ─────────────────────────────────────────────────────────────
-- FilterVerdict 는 반환값이라 트랜잭션이 끝나면 사라진다. #11 이 분석 순서를 정할 때
-- SQL 정렬로 써야 하는데 Java 함수로는 못 한다.
--
-- SMALLINT 로 충분하다 — 값은 0~100 의 등급이지 누적 점수가 아니다.
ALTER TABLE issue
    ADD COLUMN filter_priority SMALLINT;

-- ─────────────────────────────────────────────────────────────
-- 3) 판정 시각 — 운영이 낡은 판정을 고를 수 있어야 한다
-- ─────────────────────────────────────────────────────────────
-- updated_at 과 뜻이 다르다. 저쪽은 「행을 언제 건드렸나」라 재수집 때마다 움직인다.
-- 이 값은 「판정이 언제 섰나」다.
--
-- 규칙·임계를 바꾸면 기존 판정은 자동으로 무효화되지 않는다(알려진 한계).
-- 그때 이 컬럼으로 대상을 고른다 — UPDATE issue SET filter_result = NULL
--                                  WHERE filter_judged_at < :규칙_변경_시각.
-- 규칙 버전 해시로 자동화하는 것은 설정이 실제로 자주 바뀌면 그때 한다.
ALTER TABLE issue
    ADD COLUMN filter_judged_at TIMESTAMP(6) WITH TIME ZONE;

-- ─────────────────────────────────────────────────────────────
-- 4) filter_reason 은 외부 텍스트가 아니다 — TEXT 에서 내린다 (S-4)
-- ─────────────────────────────────────────────────────────────
-- 🔴 이 컬럼에 이슈 본문 발췌가 들어가면, 대상 저장소 사용자가 쓴 임의 텍스트가
--   우리 DB 를 거쳐 LLM 프롬프트·PR 본문으로 흘러간다. #7 의 contribution_rules 가
--   정확히 그랬다.
--
-- 들어가는 값을 FilterReason enum 의 name() 로 제약했으므로 외부 텍스트가 아니다.
-- 이 프로젝트에서 TEXT 는 「길어서 따로 둔 외부 텍스트」를 뜻하고 @ExternalText 마커가
-- 강제된다(ExternalTextMarkerTest) — 우리 어휘를 TEXT 로 두면 그 뜻이 흐려지고,
-- repository_policy.pending_reason 을 VARCHAR 로 둔 판단(V5)과도 어긋난다.
--
-- 길이는 설계상 유계다 — 사유 코드 6종을 전부 콤마로 이어도 100자 남짓이다.
ALTER TABLE issue
    ALTER COLUMN filter_reason SET DATA TYPE VARCHAR(512);
