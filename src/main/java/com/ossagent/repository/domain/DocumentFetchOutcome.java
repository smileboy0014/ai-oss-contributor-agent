package com.ossagent.repository.domain;

/**
 * 규약 문서 한 개를 읽으려 한 결과. <b>S-5 가 가르는 선이 여기 있다.</b>
 *
 * <p>가르는 기준은 「무슨 오류인가」가 아니라 <b>「읽었는가」</b>다. 이 셋을 하나로 뭉개면
 * 「규약이 있는데 못 읽은 것」이 「규약이 없다 → 허용」으로 번역되고, 그 순간 규약 위반 PR 이
 * 외부 OSS 로 나간다.
 *
 * <p>이 구분은 새로 만드는 것이 아니다 — {@code RepositorySource.fetchFile} 이 이미
 * 계약으로 갈라 뒀다. {@code Optional.empty()} 는 <b>404 하나뿐</b>이고 나머지는 예외다.
 */
public enum DocumentFetchOutcome {

    /** 내용을 받았다. 판정 입력이 된다 */
    READ,

    /**
     * 그 경로에 파일이 없다 (404).
     *
     * <p><b>오류가 아니라 정상 상황</b>이고, 그 사실 자체가 판정 입력이다 —
     * 없는 문서에 금지 표기가 있을 수 없다.
     */
    ABSENT,

    /**
     * 읽지 못했다 — 레이트리밋 · 5xx · 1MB 초과 · 권한 · 상한 절단 · <b>분류되지 않는 오류</b>.
     *
     * <p>🔴 판정 필수 경로에서 이것이 하나라도 나오면 <b>보류</b>다. 「아마 없겠지」로
     * 넘어가지 않는다.
     */
    UNREADABLE
}
