-- 이슈 #7 — 대상 저장소 기여 규약 수집·분석
--
-- ⚠ 머지 순서: V4(#12 후보 상태머신) → V5(여기) → V6(#8 이슈 커서).
--   baseline-on-migrate 가 false 라 순서가 역전되면 Flyway 가 out-of-order 로 보고
--   validate 에서 기동을 막는다. H2 는 매번 새로 떠서 드러나지 않고
--   PostgreSQL 개발 DB 에서만 터진다 — Q-2b 가 경고한 「H2 에서 됐다」의 전형이다.
--
-- ⚠ 벤더 고유 문법을 쓰지 않는다 (Q-2). H2·PostgreSQL 양쪽에서 같은 SQL 이 돈다.

-- ─────────────────────────────────────────────────────────────
-- 1) 보류 사유 — Q-8 확정 ②
-- ─────────────────────────────────────────────────────────────
-- ai_contribution_allowed IS NULL(보류)일 때 「왜 보류됐는지」를 남긴다.
-- 보류는 자동으로 풀리지 않고 사람이 본다. 근거가 없으면 판단할 수가 없다.
--
-- ⚠ 예외 원문을 넣지 않는다 — 우리 어휘(경로 + 사유 코드)만 (S-4).
--   HTTP 예외 본문에는 요청 URL 과 헤더가 담기고 거기 토큰이 붙어 있을 수 있다.
--
-- 🔴 TEXT 가 아니라 VARCHAR 다. 이 프로젝트에서 TEXT 는 「길어서 따로 둔 외부 텍스트」를
--   뜻하고 @ExternalText 마커가 강제된다(ExternalTextMarkerTest). 여기 들어가는 것은
--   외부 텍스트가 아니라 우리가 만든 사유 문자열이고, 길이도 설계상 유계다
--   (후보 경로 13개 × 「경로=사유코드; 」 ≈ 650자).
ALTER TABLE repository_policy
    ADD COLUMN pending_reason VARCHAR(1024);

-- ─────────────────────────────────────────────────────────────
-- 2) 실행 기록이 후보에 묶이지 않을 수 있다
-- ─────────────────────────────────────────────────────────────
-- 「모든 LLM 호출은 후보에 속한다」는 전제가 틀렸다.
-- 규약 판정(Stage.POLICY)은 저장소 단위이고 후보가 만들어지기 전에 일어난다.
--
-- 가짜 candidate_id(0·-1)로 채우면 비용 장부와 MDC 가 오염되므로 전제를 고친다.
-- AgentRun 이 독립 애그리거트라는 근거(무한정 쌓이는 append-only)는 그대로 서고,
-- NULL 허용은 그 독립성을 오히려 강화한다.
--
-- 🔴 전면 허용이 아니다 — 엔티티가 「POLICY 단계만 NULL」을 강제한다.
--   DB 제약으로는 표현하지 않는다(CHECK 로 쓰면 stage enum 문자열에 스키마가 묶인다).
ALTER TABLE agent_run
    ALTER COLUMN candidate_id DROP NOT NULL;
