package com.ossagent.agent.domain;

/**
 * 프롬프트를 모델에 보내기 <b>전에</b> 시크릿을 지우는 능력 — S-4.
 *
 * <p>{@code external-deps.md} 가 「프롬프트에 넣기 전 시크릿 스크럽 — <b>이 경로가 가장 흔한
 * 유출구다</b>」라고 적은 그 이음매다.
 *
 * <p>다른 S-4 방어(로그 미기록 · 예외 번역 · 응답 미적재)는 전부 <b>우리 안쪽</b>을 막는다.
 * 여기만이 <b>밖으로 나가는 것</b>을 막는다. 유출 상대가 모델 제공자이므로, 한 번 나가면
 * 회수 수단이 토큰 폐기·재발급뿐이다.
 *
 * <p>대상 저장소의 파일 내용을 프롬프트에 싣는 것은 소비자 이슈의 <b>일상 동작</b>이고,
 * 그 저장소가 시크릿을 커밋해 뒀을 수 있다. 소비자 4곳이 각자 기억하게 두지 않고
 * {@link LanguageModel} 구현이 반드시 통과시킨다.
 *
 * <p>구현은 {@code adapter/out/llm} 에 있고, 패턴 치환은 <b>새로 만들지 않고</b>
 * {@code support.secret.TokenRedactor} 에 위임한다 — #6 이 이미 같은 패턴 집합을 갖고 있어
 * 두 벌을 두면 한쪽만 갱신되는 순간 구멍이 생긴다. 파일 단위 배제({@code .env} · {@code *.pem} 류)는
 * #28 이 그 위에 쌓는다.
 *
 * <p>치환 표식은 {@code TokenRedactor.MASK} 하나뿐이다. <b>검색 가능한 고정 문자열</b>이어야
 * 하는 이유가 있다 — {@code CODE} 호출은 대상 저장소 파일을 프롬프트에 싣고 모델은 그 파일의
 * 패치를 낸다. 치환된 자리가 <b>모델이 생성한 패치에 실려</b> Fork 커밋과 Draft PR 까지 갈 수 있다.
 * 확률은 낮지만 결과가 외부로 나가므로, 검증 단계(#13 · #16)가 이 문자열을 찾아 변경분을
 * 실패로 판정할 수 있어야 한다. 표식이 두 종류가 되면 그 검사가 한쪽을 놓친다.
 */
public interface PromptScrubber {

    /**
     * 시크릿으로 보이는 부분을 치환한 텍스트를 돌려준다.
     *
     * <p><b>fail-closed 다</b> — 판단이 서지 않으면 남기지 말고 지운다. 토큰이 하나 나가는 비용이
     * 프롬프트가 조금 뭉개지는 비용보다 훨씬 크다.
     *
     * @param text 스크럽할 텍스트. {@code null} 이면 {@code null} 을 돌려준다
     * @return 치환된 텍스트
     */
    String scrub(String text);
}
