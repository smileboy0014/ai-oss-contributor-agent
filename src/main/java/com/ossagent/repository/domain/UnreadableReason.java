package com.ossagent.repository.domain;

/**
 * 왜 못 읽었는가. <b>우리 어휘로만</b> 남긴다 — S-4.
 *
 * <p>예외 원문을 {@code pending_reason} 에 넣지 않는 이유는 #10 에서
 * {@code AgentRun.errorMessage} 가 같은 처리를 받는 것과 같다 — HTTP 예외 본문에 요청 URL 과
 * 헤더가 담기고, 거기 토큰이 붙어 있으면 그대로 DB 에 적재된다.
 *
 * <p>사유를 코드로 가르는 실익이 하나 더 있다 — 보류 해소(#24)가 <b>일괄 재시도 대상</b>을
 * 고를 수 있다. 「레이트리밋으로 보류된 것만 다시」가 가능해야 사람이 감당할 수 있다.
 */
public enum UnreadableReason {

    /**
     * 레이트리밋.
     *
     * <p>⚠️ {@code external-deps.md} 는 「리밋 소진은 <b>정상 운영 상황</b>이고 대응은 지연」이라고
     * 규율로 둔다. 그래서 이 사유로 보류를 만들기 <b>전에 재시도</b>한다. 정상 상황을
     * 사람이 풀어야 하는 보류로 굳히지 않는다.
     */
    RATE_LIMITED,

    /** 5xx · 연결 실패 · 타임아웃. 재시도 후에도 실패했을 때만 여기 온다 */
    SERVER_ERROR,

    /** 1MB 초과 — GitHub 이 내용을 주지 않는다 */
    TOO_LARGE,

    /**
     * 설정 상한을 넘어 절단이 발생했다.
     *
     * <p>🔴 <b>절단되면 보류다.</b> 「잘린 뒷부분에 금지 문구가 있었을 수 있다」는 판정이
     * 불가능하므로 — 잘린 이상 가능성은 항상 있다 — 조건을 따지지 않는다.
     */
    TRUNCATED,

    /** 권한 · 경로가 디렉터리 · <b>우리가 분류하지 못한 오류</b> */
    UNKNOWN
}
