package com.ossagent.repository.domain;

/**
 * 이 파일을 <b>왜</b> 골랐는가 — 이슈 #15 FR-5.
 *
 * <p>이슈 본문이 못 박아 둔 요구다: 「왜 이 파일을 골랐는지 모르면 실패를 고칠 수 없다」.
 * 계획(#16)이 엉뚱한 파일을 보고 헛짚었을 때, 그것이 <b>점수 규칙의 문제인지 이슈에 신호가
 * 없었던 것인지</b>를 이 값으로 가른다.
 */
public enum SelectionReason {

    /** 이슈가 경로·파일 이름을 직접 짚었다 — 가장 믿을 만하다 */
    PATH_LITERAL,

    /** 이슈가 말한 타입 이름이 파일 이름과 맞았다 */
    TYPE_NAME,

    /** 이슈가 말한 패키지가 디렉터리와 맞았다 */
    PACKAGE,

    /** 낱말이 경로에 나타났다 — 가장 약하다 */
    TERM,

    /** 고른 소스의 <b>테스트 짝</b>이라 함께 가져왔다 (FR-3) */
    TEST_PAIR,

    /** 고른 소스가 <b>import 하는</b> 같은 저장소 파일이라 함께 가져왔다 (FR-7) */
    IMPORT_NEIGHBOR
}
