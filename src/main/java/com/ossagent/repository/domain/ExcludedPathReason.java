package com.ossagent.repository.domain;

/**
 * 후보였다가 <b>빠진</b> 이유 — 이슈 #15 FR-5 의 다른 반쪽.
 *
 * <p>고른 이유({@link SelectionReason})만 남기면 「왜 그 파일이 없지」를 답할 수 없다.
 * 선별이 빈약할 때 원인이 <b>신호 부족</b>인지 <b>예산 소진</b>인지 <b>배제</b>인지가
 * 갈리는 자리다.
 *
 * <p>🔴 이 값들은 개수로만 집계한다. 배제된 <b>경로 목록</b>을 값에 싣지 않는다 —
 * 시크릿 경로 이름 자체가 정보이고, 수천 건이 될 수 있다.
 */
public enum ExcludedPathReason {

    /**
     * 🔴 {@code SecretFilePolicy} 가 막았다 — S-4.
     *
     * <p>이 경로는 <b>읽지도 않는다.</b> 내용 스크럽보다 앞선 방어다.
     */
    SECRET_PATH,

    /** 소스로 보지 않는 확장자·경로(빌드 산출물 등) */
    NOT_SOURCE,

    /** 트리가 알려준 크기가 파일당 상한을 넘었다 — <b>읽기 전에</b> 걸렀다 */
    TOO_LARGE,

    /** 트리에는 있었는데 읽을 때 404 였다 — 그 사이에 지워졌거나 ref 가 어긋났다 */
    NOT_FOUND,

    /**
     * 읽었으나 <b>내용을 쓸 수 없었다</b> — 1MB 초과 · 디렉터리 · 심볼릭링크 · 디코드 실패.
     *
     * <p>🔴 {@link #NOT_FOUND} 와 가르는 것이 중요하다. 저쪽은 「없다」이고 이쪽은
     * <b>「있는데 못 읽었다」</b>다. 규약 판정(S-5)에서 이 구분이 무너지면 위반 PR 이 나가는데,
     * 여기서는 그 정도는 아니어도 <b>같은 이름으로 부르지 않는다</b> — 용어가 흐려지면
     * 다음 소비자가 뭉갠다.
     */
    UNREADABLE,

    /** 점수는 됐는데 파일 수·문자 예산이 남지 않았다 (FR-4) */
    BUDGET_EXHAUSTED
}
